"""Turn outputs/test_run.txt into LaTeX macros, so the text cannot drift from the run.

Usage: python3 -I scripts/make_macros.py outputs/test_run.txt sections/testnums.tex
"""
import ast
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
out = []


def fmt(n):
    return "{:,}".format(int(n)).replace(",", "{,}")


def macro(name, val):
    out.append("\\newcommand{\\%s}{%s}" % (name, fmt(val)))


names = {"SPEC": "Spec", "SPEC + lift cap": "Cap", "MUTANT lock rounds down": "Lock",
         "MUTANT no floor guard": "Floor", "MUTANT debt cap at spot": "Spot"}
total_ops = 0
for line in open(src):
    m = re.match(r"(.+?)\s+episodes=\s*(\d+) executed_ops=\s*(\d+) failing_episodes=\s*(\d+)\s*(\{.*\})?", line)
    if m and m.group(1).strip() in names:
        k = names[m.group(1).strip()]
        macro("T%sEp" % k, m.group(2)); macro("T%sOps" % k, m.group(3)); macro("T%sFail" % k, m.group(4))
        tally = ast.literal_eval(m.group(5)) if m.group(5) else {}
        if k in ("Spec", "Cap"):
            total_ops += int(m.group(3))
            assert not tally and m.group(4) == "0", "specification run has violations"
        for key, short in [("J2 loan cover", "JTwo"), ("coverage", "Cov"), ("floor decreased", "Dec")]:
            macro("T%s%s" % (k, short), tally.get(key, 0))
        macro("T%sLiq" % k, sum(v for kk, v in tally.items() if kk.startswith("liquidity refusal")))
        macro("T%sLiqMax" % k, max([v for kk, v in tally.items() if kk.startswith("liquidity refusal")] or [0]))
    m = re.match(r"mint-reshape-redeem lift_cap=(\w+)\s+trials=(\d+) reshape_refused=(\d+) profitable=(\d+)", line)
    if m:
        k = "RCap" if m.group(1) == "True" else "RNo"
        macro("T%sTrials" % k, m.group(2)); macro("T%sRefused" % k, m.group(3)); macro("T%sWins" % k, m.group(4))
    m = re.match(r"sandwich profit bound\s+trials=(\d+) violations=(\d+)", line)
    if m:
        macro("TSandTrials", m.group(1)); macro("TSandViol", m.group(2))
    if line.startswith("RESULT:"):
        assert "PASS" in line, "test run did not pass"
macro("TTotalOps", total_ops)
text = open(src).read()
required = list(names) + ["mint-reshape-redeem lift_cap=False", "mint-reshape-redeem lift_cap=True",
                          "sandwich profit bound", "directed boundary tests    failures=0",
                          "RESULT: PASS"]
for key in required:
    if key in names:                      # a run line: the name, then "episodes="
        hits = [ln for ln in text.splitlines()
                if ln.startswith(key) and ln[len(key):].lstrip().startswith("episodes=")]
    else:
        hits = [ln for ln in text.splitlines() if ln.startswith(key)]
    assert len(hits) == 1, "missing or repeated record: " + key
assert len(out) == 49, "unexpected number of macros: %d" % len(out)
open(dst, "w").write("% generated by scripts/make_macros.py from " + src + "\n" + "\n".join(out) + "\n")
print("wrote", len(out), "macros; total spec ops", total_ops)

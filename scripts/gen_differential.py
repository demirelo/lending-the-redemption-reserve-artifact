"""Generate a Foundry test that replays random traces of the Python reference
model against the Solidity contract and compares the complete aggregate state
after every operation.

Usage: python3 -I scripts/gen_differential.py 24 160 > contracts/test/Differential.t.sol
"""
import copy
import random
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
from dabc_model import DABC, Revert, WAD, BPS  # noqa: E402

TRACES = int(sys.argv[1]) if len(sys.argv) > 1 else 24
OPS = int(sys.argv[2]) if len(sys.argv) > 2 else 160
rng = random.Random(2026)
KIND = {"buy": 0, "sell": 1, "borrow": 2, "repay": 3, "close": 4, "raise": 5,
        "skim": 6, "gamma": 7, "inflow": 8, "reshape": 9}


def reshape_candidate(m):
    """A replacement schedule derived from the current one: some admissible, some not."""
    new = [list(x) for x in m.steps]
    how = rng.choice(["tail_up", "tail_up", "mid_up", "cap", "append", "floor_up", "floor_down", "split"])
    i = rng.randrange(len(new))
    if how == "tail_up":
        new[-1][0] += rng.choice([1, new[-1][0] // 200 + 1, new[-1][0] // 20 + 1])
    elif how == "mid_up":
        new[i][0] += rng.choice([1, new[i][0] // 500 + 1, new[i][0] // 50 + 1])
    elif how == "cap":
        new[-1][1] = max(0, new[-1][1] + rng.choice([-new[-1][1], -1, 1, 500]))
    elif how == "append" and len(new) < 60:
        new.append([new[-1][0] + rng.choice([0, 1, new[-1][0] // 10 + 1]), rng.randint(1, 2000)])
    elif how == "floor_up":
        new[0][0] += rng.choice([1, new[0][0] // 1000 + 1, new[0][0] // 100 + 1])
    elif how == "floor_down":
        new[0][0] = max(1, new[0][0] - rng.choice([1, new[0][0] // 100 + 1]))
    elif how == "split" and new[i][1] > 1 and len(new) < 60:
        c = rng.randint(1, new[i][1] - 1)
        new[i:i + 1] = [[new[i][0], c], [new[i][0], new[i][1] - c]]
    return new, rng.choice([0, 0, 0, rng.randint(1, 3000)])


def curve():
    pf = rng.choice([WAD, 2 * WAD, WAD // 3 + 1, 7 * WAD // 5, 3 * 10**17 + 7])
    steps, p = [[pf, rng.randint(1, 5000)]], pf
    for _ in range(rng.randint(1, 5)):
        p += rng.choice([1, pf // 97 + 1, pf // 10 + 3, pf // 2])
        steps.append([p, rng.randint(1, 3000)])
    return steps


out = ['''// SPDX-License-Identifier: MIT
// GENERATED by scripts/gen_differential.py -- do not edit.
pragma solidity ^0.8.24;

import {Test} from "forge-std/Test.sol";
import {FloorCreditIssuer, IERC20Like} from "../src/FloorCreditIssuer.sol";
import {MockReserve} from "./MockReserve.sol";

/// @notice Replays traces of the Python reference model and requires the
///         contract to agree on success/failure, on (S, A, L, D, Pf, surplus, capacity,
///         gamma, token balance) and on the acting account's free balance, lock and debt.
contract DifferentialTest is Test {
    FloorCreditIssuer m;
    MockReserve reserve;
    address gov = address(0x60);
    uint256 public replayed;

    function _deploy(FloorCreditIssuer.Step[] memory s, uint256 gc, uint256 g, uint256 fb, uint256 fs, uint256 fo) internal {
        reserve = new MockReserve();
        m = new FloorCreditIssuer(IERC20Like(address(reserve)), gov, address(0x7EA), s, FloorCreditIssuer.Params(gc, g, fb, fs, fo, 0));
        for (uint160 u = 0; u < 5; u++) {
            address a = u == 4 ? gov : address(0xA1 + u);
            reserve.mint(a, 1e40);
            vm.prank(a);
            reserve.approve(address(m), type(uint256).max);
        }
    }

    /// Replace the schedule with the steps given as (price, capacity) pairs in `f`.
    function _reshape(uint160 u, uint256[] memory f, uint256 inject, bool ok, uint256[11] memory st) internal {
        FloorCreditIssuer.Step[] memory s = new FloorCreditIssuer.Step[](f.length / 2);
        for (uint256 i = 0; i < s.length; i++) {
            s[i] = FloorCreditIssuer.Step(f[2 * i], f[2 * i + 1]);
        }
        bool done;
        vm.prank(gov);
        try m.reshape(s, inject) { done = true; } catch {}
        _check(address(0xA1 + u), done, ok, st);
    }

    /// kind: 0 buy, 1 sell, 2 borrow, 3 repay, 4 close, 5 raise, 6 skim, 7 gamma, 8 inflow
    function _op(uint8 kind, uint160 u, uint256 a, uint256 b, bool ok, uint256[11] memory st) internal {
        address who = address(0xA1 + u);
        bool done;
        if (kind == 0) { vm.prank(who); try m.buy(a, type(uint256).max) { done = true; } catch {} }
        else if (kind == 1) { vm.prank(who); try m.sell(a, 0) { done = true; } catch {} }
        else if (kind == 2) { vm.prank(who); try m.borrow(a, b, 0) { done = true; } catch {} }
        else if (kind == 3) { vm.prank(who); try m.repay(a) { done = true; } catch {} }
        else if (kind == 4) { vm.prank(who); try m.close(0) { done = true; } catch {} }
        else if (kind == 5) { try m.raiseFloor(a) { done = true; } catch {} }
        else if (kind == 6) { vm.prank(gov); try m.skim(a) { done = true; } catch {} }
        else if (kind == 7) { vm.prank(gov); try m.setGamma(a) { done = true; } catch {} }
        else { vm.prank(gov); try m.contribute(a) { done = true; } catch {} }
        _check(who, done, ok, st);
    }

    function _check(address who, bool done, bool ok, uint256[11] memory st) internal {
        assertEq(done, ok, "success flag");
        assertEq(m.totalSupply(), st[0], "S");
        assertEq(m.cash(), st[1], "A");
        assertEq(m.totalLocked(), st[2], "L");
        assertEq(m.totalDebt(), st[3], "D");
        assertEq(m.floorPrice(), st[4], "Pf");
        assertEq(m.surplus(), st[5], "surplus");
        assertEq(reserve.balanceOf(address(m)), st[1], "balance");
        assertEq(m.capacity(), st[6], "capacity");
        assertEq(m.gammaBps(), st[7], "gamma");
        assertEq(m.balanceOf(who), st[8], "free balance of the acting account");
        (uint256 l, uint256 d) = m.loans(who);
        assertEq(l, st[9], "lock of the acting account");
        assertEq(d, st[10], "debt of the acting account");
        replayed++;
    }
''']

total = 0
reshapes = {True: 0, False: 0}
for t in range(TRACES):
    cap = rng.choice([5000, 8000, 9000])
    fs = rng.choice([0, 30, 100, 750])
    while cap + fs >= BPS:
        fs = 0
    cfg = dict(gamma_cap_bps=cap, gamma_bps=rng.randint(1, cap), fee_buy_bps=rng.choice([0, 30, 100, 300]),
               fee_sell_bps=fs, fee_orig_bps=rng.choice([0, 100, 300]))
    steps = curve()
    m = DABC(steps, lift_cap=True, **cfg)
    lines = [f"    function test_trace{t}() public {{",
             f"        FloorCreditIssuer.Step[] memory s = new FloorCreditIssuer.Step[]({len(steps)});"]
    for i, (p, c) in enumerate(steps):
        lines.append(f"        s[{i}] = FloorCreditIssuer.Step({p}, {c});")
    lines.append(f"        _deploy(s, {cfg['gamma_cap_bps']}, {cfg['gamma_bps']}, {cfg['fee_buy_bps']}, "
                 f"{cfg['fee_sell_bps']}, {cfg['fee_orig_bps']});")
    lines.append("        uint256[] memory f;")
    for _ in range(OPS):
        u = rng.randint(0, 3)
        op = rng.choice(["buy"] * 4 + ["sell"] * 3 + ["borrow"] * 5 + ["repay"] * 2
                        + ["close", "raise", "raise", "skim", "gamma", "inflow", "reshape"])
        snap = copy.deepcopy(m.__dict__)
        a = b = 0
        cand = None
        try:
            if op == "reshape":
                cand, a = reshape_candidate(m)
                m.reconfigure(cand, a)
            elif op == "buy":
                a = rng.randint(1, max(1, (m.capacity() - m.S) // rng.choice([1, 3, 20])))
                m.buy(u, a)
            elif op == "sell":
                bal = m.bal.get(u, 0)
                a = rng.choice([bal, rng.randint(1, max(1, bal))])
                m.sell(u, a)
            elif op == "borrow":
                l, d = m.loans.get(u, (0, 0))
                a = rng.choice([0, rng.randint(0, m.bal.get(u, 0))])
                mx = m.gamma_bps * m.Pf * (l + a) // (BPS * WAD) - d
                b = rng.randint(1, max(1, mx + 1))
                m.borrow(u, a, b)
            elif op == "repay":
                d = m.loans.get(u, (0, 0))[1]
                a = rng.choice([d, rng.randint(1, max(1, d))])
                m.repay(u, a)
            elif op == "close":
                m.close(u)
            elif op == "raise":
                sp = m.surplus()
                a = rng.choice([sp, rng.randint(1, max(1, sp))])
                m.raise_floor(a)
            elif op == "skim":
                sp = m.surplus()
                a = rng.choice([sp, rng.randint(1, max(1, sp))])
                m.skim(a)
            elif op == "gamma":
                a = rng.randint(1, m.gamma_cap_bps + 50)
                m.set_gamma(a)
            else:
                a = rng.randint(1, 500)
                m.donate(a)
            ok = True
        except Revert:
            m.__dict__.update(snap)
            ok = False
        assert not m.check()
        lu, du = m.loans.get(u, (0, 0))
        st = (f"[uint256({m.S}), {m.A}, {m.L}, {m.D}, {m.Pf}, {m.surplus()}, {m.capacity()}, "
              f"{m.gamma_bps}, {m.bal.get(u, 0)}, {lu}, {du}]")
        if cand is not None:
            flat = [v for step in cand for v in step]
            lines.append(f"        f = new uint256[]({len(flat)});")
            lines.append("        " + " ".join(f"f[{i}] = {v};" for i, v in enumerate(flat)))
            lines.append(f"        _reshape({u}, f, {a}, {'true' if ok else 'false'}, {st});")
            reshapes[ok] += 1
        else:
            lines.append(f"        _op({KIND[op]}, {u}, {a}, {b}, {'true' if ok else 'false'}, {st});")
        total += 1
    lines.append("    }\n")
    out.append("\n".join(lines))
out.append("}\n")
sys.stdout.write("\n".join(out))
sys.stderr.write(f"generated {TRACES} traces, {total} operations, of which {reshapes[True]} accepted and "
                 f"{reshapes[False]} refused schedule replacements\n")
